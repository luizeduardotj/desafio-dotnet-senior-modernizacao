-- Schema NFSE_OWNER - Nota Carioca (replica didatica)
SET DEFINE OFF
WHENEVER SQLERROR EXIT FAILURE

CREATE SEQUENCE SEQ_CONTRIBUINTES START WITH 100000 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_NFSE START WITH 1 INCREMENT BY 1 CACHE 1000;
CREATE SEQUENCE SEQ_RPS START WITH 1 INCREMENT BY 1 CACHE 1000;
CREATE SEQUENCE SEQ_GUIAS START WITH 1 INCREMENT BY 1 CACHE 100;
CREATE SEQUENCE SEQ_PROTOCOLO START WITH 1000 INCREMENT BY 1 NOCACHE;

CREATE TABLE CONTRIBUINTES (
    ID                   NUMBER           NOT NULL,
    INSCRICAO_MUNICIPAL  VARCHAR2(8)      NOT NULL,
    DOCUMENTO            VARCHAR2(14)     NOT NULL,
    RAZAO_SOCIAL         VARCHAR2(150),
    REGIME               CHAR(1)          DEFAULT 'N' NOT NULL,
    ATIVO                CHAR(1)          DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_CONTRIBUINTES PRIMARY KEY (ID),
    CONSTRAINT UK_CONTRIB_IM UNIQUE (INSCRICAO_MUNICIPAL),
    CONSTRAINT CK_CONTRIB_REGIME CHECK (REGIME IN ('N','S','M')),
    CONSTRAINT CK_CONTRIB_ATIVO CHECK (ATIVO IN ('S','N'))
);

CREATE TABLE ITENS_SERVICO (
    CODIGO     VARCHAR2(5)    NOT NULL,
    DESCRICAO  VARCHAR2(200),
    ALIQUOTA   NUMBER(5,4)    NOT NULL,
    CONSTRAINT PK_ITENS_SERVICO PRIMARY KEY (CODIGO)
);

CREATE TABLE LOTES_RPS (
    PROTOCOLO          VARCHAR2(30)  NOT NULL,
    PRESTADOR_ID       NUMBER        NOT NULL,
    NUMERO_LOTE        NUMBER,
    QTD_RPS            NUMBER,
    SITUACAO           NUMBER(1)     DEFAULT 1 NOT NULL,
    XML_LOTE           CLOB,
    ERROS              CLOB,
    DT_RECEBIMENTO     DATE,
    DT_PROCESSAMENTO   DATE,
    CONSTRAINT PK_LOTES_RPS PRIMARY KEY (PROTOCOLO),
    CONSTRAINT FK_LOTES_PRESTADOR FOREIGN KEY (PRESTADOR_ID) REFERENCES CONTRIBUINTES (ID),
    CONSTRAINT CK_LOTES_SITUACAO CHECK (SITUACAO IN (1,2,3,4))
);
CREATE INDEX IX_LOTES_SITUACAO ON LOTES_RPS (SITUACAO);

CREATE TABLE RPS (
    ID             NUMBER        NOT NULL,
    PRESTADOR_ID   NUMBER        NOT NULL,
    NUMERO         NUMBER        NOT NULL,
    SERIE          VARCHAR2(5),
    TIPO           NUMBER(1),
    DT_EMISSAO     DATE,
    PROTOCOLO      VARCHAR2(30),
    TOMADOR_CNPJ   NUMBER(14),
    TOMADOR_CPF    NUMBER(11),
    TOMADOR_RAZAO  VARCHAR2(150),
    NFSE_ID        NUMBER,
    CONSTRAINT PK_RPS PRIMARY KEY (ID),
    CONSTRAINT FK_RPS_PRESTADOR FOREIGN KEY (PRESTADOR_ID) REFERENCES CONTRIBUINTES (ID)
);
CREATE INDEX IX_RPS_PRESTADOR_NUM ON RPS (PRESTADOR_ID, SERIE, NUMERO);
CREATE INDEX IX_RPS_PROTOCOLO ON RPS (PROTOCOLO);

CREATE TABLE NFSE (
    ID                     NUMBER          NOT NULL,
    PRESTADOR_ID           NUMBER          NOT NULL,
    NUMERO                 NUMBER          NOT NULL,
    CODIGO_VERIFICACAO     VARCHAR2(9),
    DT_EMISSAO             DATE,
    COMPETENCIA            DATE,
    ITEM_SERVICO           VARCHAR2(5),
    DISCRIMINACAO          VARCHAR2(2000),
    VALOR_SERVICOS         NUMBER(15,2),
    VALOR_DEDUCOES         NUMBER(15,2)    DEFAULT 0,
    BASE_CALCULO           NUMBER(15,2),
    ALIQUOTA               NUMBER(5,4),
    VALOR_ISS              NUMBER(15,2),
    ISS_RETIDO             CHAR(1),
    TOMADOR_DOCUMENTO      VARCHAR2(14),
    TOMADOR_RAZAO          VARCHAR2(150),
    SITUACAO               CHAR(1)         DEFAULT 'N',
    DT_CANCELAMENTO        DATE,
    MOTIVO_CANCELAMENTO    VARCHAR2(255),
    NFSE_SUBSTITUIDORA_ID  NUMBER,
    RPS_ID                 NUMBER,
    CONSTRAINT PK_NFSE PRIMARY KEY (ID),
    CONSTRAINT UK_NFSE_NUMERO UNIQUE (PRESTADOR_ID, NUMERO)
);
CREATE INDEX IX_NFSE_TOMADOR_DT ON NFSE (TOMADOR_DOCUMENTO, DT_EMISSAO);
CREATE INDEX IX_NFSE_PRESTADOR_COMP ON NFSE (PRESTADOR_ID, COMPETENCIA);

CREATE TABLE GUIAS (
    ID              NUMBER         NOT NULL,
    PRESTADOR_ID    NUMBER         NOT NULL,
    COMPETENCIA     DATE           NOT NULL,
    VALOR_ISS       NUMBER(15,2),
    SITUACAO        CHAR(1)        DEFAULT 'A',
    DT_VENCIMENTO   DATE,
    DT_ATUALIZACAO  DATE,
    CONSTRAINT PK_GUIAS PRIMARY KEY (ID),
    CONSTRAINT UK_GUIAS_PREST_COMP UNIQUE (PRESTADOR_ID, COMPETENCIA)
);

EXIT
