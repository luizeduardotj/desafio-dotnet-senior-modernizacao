-- Executar como SYSTEM (ou DBA) conectado ao PDB do Nota Carioca.
-- Grants sempre diretos, nunca por role: views e pacotes com definer rights ignoram roles (ADR-0002).
WHENEVER SQLERROR EXIT FAILURE

CREATE USER NFSE_MODERNO IDENTIFIED BY "&senha_moderno" QUOTA 0 ON USERS;
GRANT CREATE SESSION, CREATE VIEW, CREATE PROCEDURE TO NFSE_MODERNO;

CREATE USER NFSE_MODERNO_APP IDENTIFIED BY "&senha_app";
GRANT CREATE SESSION TO NFSE_MODERNO_APP;

CREATE USER NFSE_MODERNO_RO IDENTIFIED BY "&senha_ro";
GRANT CREATE SESSION TO NFSE_MODERNO_RO;

EXIT
