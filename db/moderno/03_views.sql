-- Executar como NFSE_MODERNO. Views finas: só projeção e junção, nenhuma regra nem tradução (ADR-0002).
WHENEVER SQLERROR EXIT FAILURE

CREATE OR REPLACE VIEW V_NFSE AS
SELECT n.ID, n.PRESTADOR_ID, n.NUMERO, n.CODIGO_VERIFICACAO, n.DT_EMISSAO, n.COMPETENCIA, n.ITEM_SERVICO,
       n.DISCRIMINACAO, n.VALOR_SERVICOS, n.VALOR_DEDUCOES, n.BASE_CALCULO, n.ALIQUOTA, n.VALOR_ISS, n.ISS_RETIDO,
       n.TOMADOR_DOCUMENTO, n.TOMADOR_RAZAO, n.SITUACAO, n.DT_CANCELAMENTO, n.MOTIVO_CANCELAMENTO,
       n.NFSE_SUBSTITUIDORA_ID,
       s.NUMERO AS NUMERO_SUBSTITUIDORA,
       p.DOCUMENTO AS PRESTADOR_DOCUMENTO, p.INSCRICAO_MUNICIPAL AS PRESTADOR_IM, p.RAZAO_SOCIAL AS PRESTADOR_RAZAO
  FROM NFSE_OWNER.NFSE n
  JOIN NFSE_OWNER.CONTRIBUINTES p ON p.ID = n.PRESTADOR_ID
  LEFT JOIN NFSE_OWNER.NFSE s ON s.ID = n.NFSE_SUBSTITUIDORA_ID;

CREATE OR REPLACE VIEW V_CONTRIBUINTE AS
SELECT ID, INSCRICAO_MUNICIPAL, DOCUMENTO, RAZAO_SOCIAL, REGIME, ATIVO
  FROM NFSE_OWNER.CONTRIBUINTES;

CREATE OR REPLACE VIEW V_GUIA AS
SELECT ID, PRESTADOR_ID, COMPETENCIA, VALOR_ISS, SITUACAO, DT_VENCIMENTO, DT_ATUALIZACAO
  FROM NFSE_OWNER.GUIAS;

GRANT READ ON V_NFSE TO NFSE_MODERNO_APP;
GRANT READ ON V_CONTRIBUINTE TO NFSE_MODERNO_APP;
GRANT READ ON V_GUIA TO NFSE_MODERNO_APP;
GRANT READ ON V_NFSE TO NFSE_MODERNO_RO;
GRANT READ ON V_CONTRIBUINTE TO NFSE_MODERNO_RO;
GRANT READ ON V_GUIA TO NFSE_MODERNO_RO;

EXIT
